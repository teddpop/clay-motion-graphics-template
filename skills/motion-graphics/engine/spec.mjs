#!/usr/bin/env node
// video.json → everything the template needs.   node spec.mjs <project-dir>
//   writes  video.js        window.VIDEO = { ...video.json, palette: <resolved palette> }
//           script.json     VO lines for vo.mjs (derived from video.json script + voice; don't edit by hand)
//           composition.html  thin shell that loads the style (only if missing or generated earlier)
//           music.js        window.MUSIC = null placeholder until compose.py writes the real one
// Palette: brand.hue → retone.py (demo saturation, re-toned) → derived tints; brand.palette entries override.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(process.argv[2] || '.');
const V = JSON.parse(fs.readFileSync(path.join(dir, 'video.json'), 'utf8'));
const style = V.style || 'clay-story';
const SCENES = fs.readdirSync(path.join(here, 'scenes')).filter((f) => f.endsWith('.js') && f !== 'index.js').map((f) => f.replace(/\.js$/, ''));

// ---------- palette ----------
const hex = (c) => { c = c.replace('#', ''); return [0, 2, 4].map((i) => parseInt(c.slice(i, i + 2), 16)); };
const toHex = (a) => '#' + a.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('').toUpperCase();
const mix = (a, b, p) => toHex(hex(a).map((v, i) => v + (hex(b)[i] - v) * p));
const lum = (c) => { const [r, g, b] = hex(c).map((v) => { v /= 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
let base = {};
if (V.brand?.hue != null) {
  const r = JSON.parse(execFileSync('python3', [path.join(here, 'retone.py'), String(V.brand.hue)], { encoding: 'utf8' }));
  base = { paper: r.paper, warm: r.sage, hi: r.hi, ink: r.ink };
}
const o = V.brand?.palette || {};
const P = { paper: '#F8F4F1', warm: '#E1D3CA', hi: '#FE8505', ink: '#191715', ...base, ...o };
P.accent = o.accent || V.brand?.accent || '#4FA046';
P.hi2 ??= mix(P.hi, '#FFFFFF', 0.45);
P.tint ??= mix(P.hi, '#FFFFFF', 0.75);
P.tint2 ??= mix(P.accent, '#FFFFFF', 0.78);
P.muted ??= mix(P.ink, P.paper, 0.6);
P.sub ??= mix(P.ink, P.paper, 0.42);
P.line ??= mix(P.paper, P.warm, 0.45);
P.line2 ??= mix(P.paper, P.warm, 0.6);
P.ok ??= '#3E9B5F';
P.onHi ??= lum(P.hi) > 0.3 ? P.ink : '#FFFFFF';
const darkHi = lum(P.hi) < 0.45;
P.kickInk ??= darkHi ? '#FFFFFF' : P.ink;
P.kickMuted ??= darkHi ? mix(P.hi, '#FFFFFF', 0.65) : mix(P.hi, P.ink, 0.4);
P.dread ??= '#3B3F73';
P.bubble ??= '#EFEDE7';
P.name = V.product.name;

// ---------- validation (fail early with a useful message) ----------
const errs = [];
const ids = new Set(V.script.map((l) => l.id));
const castIds = new Set((V.cast || [V.mascot || {}]).map((c, i) => c.id || (i ? 'c' + i : 'main')));
if (!V.scenes?.length) errs.push('scenes: missing — the Director composes the film as a list of scenes (references/scenes.md)');
const used = new Set();
(V.scenes || []).forEach((sc, i) => {
  if (!SCENES.includes(sc.scene)) errs.push(`scenes[${i}]: unknown scene "${sc.scene}" (have: ${SCENES.join(', ')})`);
  for (const l of sc.lines || []) { if (!ids.has(l)) errs.push(`scenes[${i}] (${sc.scene}): line "${l}" not in script`); used.add(l); }
  if (!sc.lines?.length) errs.push(`scenes[${i}] (${sc.scene}): needs "lines"`);
  for (const st of sc.steps || []) { if (!ids.has(st.line)) errs.push(`scenes[${i}] step: line "${st.line}" not in script`); used.add(st.line); if (st.screen && !V.screens?.[st.screen]) errs.push(`scenes[${i}] step: screen "${st.screen}" not in screens`); }
  if (sc.screen && !V.screens?.[sc.screen]) errs.push(`scenes[${i}] (${sc.scene}): screen "${sc.screen}" not in screens`);
});
for (const l of V.script) { if (!used.has(l.id)) errs.push(`script line "${l.id}" isn't used by any scene`); if (l.speaker && !castIds.has(l.speaker)) errs.push(`script line "${l.id}": speaker "${l.speaker}" not in cast`); }
if (V.scenes?.length && V.scenes.at(-1).scene !== 'end') errs.push('the last scene should be "end"');
const words = V.script.reduce((a, l) => a + l.say.split(/\s+/).length, 0);
if (errs.length) { console.error(errs.map((e) => '  ✗ ' + e).join('\n')); process.exit(1); }

fs.writeFileSync(path.join(dir, 'video.js'), `// generated by spec.mjs from video.json — do not edit\nwindow.VIDEO = ${JSON.stringify({ ...V, palette: P }, null, 1)};\n`);

// ---------- script.json for vo.mjs ----------
const vo = V.voice || {};
const narr = (V.cast || [])[0] || V.mascot || {};
const script = { engine: 'kokoro', voice: vo.voice || narr.voice || 'af_heart', speed: vo.speed ?? narr.speed ?? 1.0, lead: vo.lead ?? 0.6, gap: vo.gap ?? 0.35, tail: vo.tail ?? 4.4, fps: 30,
  lines: V.script.map((l) => { const sp = l.speaker && (V.cast || []).find((c) => c.id === l.speaker);
    return { id: l.id, say: l.say, pauseAfter: l.pauseAfter ?? 0.35, ...(l.voice || sp?.voice ? { voice: l.voice || sp.voice } : {}), ...(l.speed || sp?.speed ? { speed: l.speed || sp.speed } : {}) }; }) };
fs.writeFileSync(path.join(dir, 'script.json'), JSON.stringify(script, null, 1) + '\n');

// ---------- composition shell ----------
const comp = path.join(dir, 'composition.html');
const rel = encodeURI(path.relative(dir, here).split(path.sep).join('/'));
const shell = `<!doctype html>
<html>
<!-- generated by spec.mjs (style: ${style}). The film = video.json "scenes"; look & feel = engine/style/${style}/; scenes = engine/scenes/. -->
<head>
<meta charset="utf-8">
<link rel="stylesheet" href="${rel}/base.css">
<link rel="stylesheet" href="${rel}/style/${style}/style.css">
<script type="importmap">{"imports":{"three":"${rel}/vendor/three/three.module.js","three/addons/":"${rel}/vendor/three/addons/"}}</script>
</head>
<body>
<div class="stage" id="root"></div>
<script src="${rel}/runtime.js"></script>
<script src="${rel}/fx.js"></script>
<script src="timing.js"></script>
<script src="video.js"></script>
<script src="music.js"></script>
<script>window.__ready = false;</script>
<script type="module" src="${rel}/style/${style}/film.js"></script>
</body>
</html>
`;
if (!fs.existsSync(comp) || fs.readFileSync(comp, 'utf8').includes('generated by spec.mjs')) fs.writeFileSync(comp, shell);
const mjs = path.join(dir, 'music.js');
if (!fs.existsSync(mjs)) fs.writeFileSync(mjs, 'window.MUSIC = null;\n');
console.log(`spec: ${V.product.name} — ${V.script.length} lines, ${words} words (~${(words / 2.9).toFixed(0)} s of speech + pauses), scenes: ${V.scenes.map((s) => s.scene).join(' → ')}, palette hi ${P.hi}`);
